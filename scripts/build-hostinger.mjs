#!/usr/bin/env node
/**
 * Build a static copy of the site for Hostinger (Apache + PHP shared hosting).
 *
 *   node scripts/build-hostinger.mjs [outDir]
 *
 * Works on a temporary copy of the repo, so the Vercel/Next setup is untouched:
 *  - next.config: output "export" (redirects and headers move to .htaccess)
 *  - server-only routes are replaced: /api/contact and /api/newsletter by
 *    api/contact.php (emails each lead), /case?id= by .htaccess redirects
 *  - writes .htaccess (www + https, clean URLs, redirects, security headers, 404)
 * The result (default: ./hostinger-build) is what goes into public_html.
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.resolve(process.argv[2] || path.join(ROOT, "hostinger-build"));
const TMP = path.join(ROOT, ".hostinger-tmp");
fs.rmSync(TMP, { recursive: true, force: true });
fs.mkdirSync(TMP);
const sh = (cmd, cwd = TMP) => execSync(cmd, { cwd, stdio: "inherit" });

console.log("Copying source to", TMP);
const SKIP = new Set(["node_modules", ".next", ".git", "out", "hostinger-build", ".hostinger-tmp"]);
for (const f of fs.readdirSync(ROOT)) if (!SKIP.has(f)) fs.cpSync(path.join(ROOT, f), path.join(TMP, f), { recursive: true });

// 1. next.config: static export, keep the redirect list for .htaccess.
const cfgPath = path.join(TMP, "next.config.ts");
let cfg = fs.readFileSync(cfgPath, "utf8");
const redirects = [...cfg.matchAll(/\{\s*source:\s*"([^"]+)",\s*destination:\s*"([^"]+)",\s*permanent:\s*true\s*\}/g)].map((m) => [m[1], m[2]]);
cfg = cfg.replace("const nextConfig: NextConfig = {", 'const nextConfig: NextConfig = {\n  output: "export",');
cfg = cfg.replace("export default nextConfig;", "delete (nextConfig as Record<string, unknown>).redirects;\ndelete (nextConfig as Record<string, unknown>).headers;\nexport default nextConfig;");
fs.writeFileSync(cfgPath, cfg);

// 2. Server-only routes.
fs.rmSync(path.join(TMP, "src/app/api"), { recursive: true, force: true });
fs.rmSync(path.join(TMP, "src/app/case"), { recursive: true, force: true });
// Every route handler and metadata route must be static for "output: export".
const appDir = path.join(TMP, "src/app");
const routeFiles = fs.readdirSync(appDir, { recursive: true }).map(String)
  .filter((f) => /(^|\/)route\.ts$/.test(f) || /^(robots|sitemap|manifest)\.ts$/.test(f));
for (const f of routeFiles) {
  const p = path.join(appDir, f);
  const src = fs.readFileSync(p, "utf8");
  if (!/export const dynamic/.test(src)) fs.writeFileSync(p, 'export const dynamic = "force-static";\n' + src);
}

// 3. Old /case?id=<post> links: id -> case page slug.
fs.writeFileSync(path.join(TMP, "case-map.mts"), `import { CASE_INDEX } from "./src/data/casePages";\nconsole.log(JSON.stringify(CASE_INDEX.map((c) => [c.id, c.slug])));\n`);
const caseMap = JSON.parse(execSync("npx tsx case-map.mts", { cwd: TMP }).toString());

// 4. Build.
for (let i = 1; ; i++) {
  try {
    sh("npx next build");
    break;
  } catch (e) {
    if (i >= 3) throw e;
    console.log("Build failed, retrying", i);
  }
}
fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(path.join(TMP, "out"), OUT, { recursive: true });

// 5. PHP lead handler (replaces /api/contact and /api/newsletter).
fs.mkdirSync(path.join(OUT, "api"), { recursive: true });
fs.copyFileSync(path.join(ROOT, "scripts/hostinger/contact.php"), path.join(OUT, "api/contact.php"));
if (!fs.existsSync(path.join(OUT, "api/config.php"))) fs.copyFileSync(path.join(ROOT, "scripts/hostinger/config.php"), path.join(OUT, "api/config.php"));

// 6. .htaccess
const rx = (s) => s.replace(/^\//, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const lines = [
  "# Generated by scripts/build-hostinger.mjs: do not edit by hand.",
  "Options -MultiViews -Indexes",
  "DirectorySlash Off",
  "DirectoryIndex index.html",
  "ErrorDocument 404 /404.html",
  "",
  "RewriteEngine On",
  "",
  "# One canonical host: https://www.funnelsthatprint.com",
  "RewriteCond %{HTTPS} off [OR]",
  "RewriteCond %{HTTP_HOST} !^www\\. [NC]",
  "RewriteRule ^ https://www.funnelsthatprint.com%{REQUEST_URI} [L,R=301]",
  "",
  "# Drop trailing slashes (except the home page)",
  "RewriteCond %{REQUEST_URI} !^/$",
  "RewriteRule ^(.+)/$ /$1 [L,R=301]",
  "",
  "# Lead forms",
  "RewriteRule ^api/(contact|newsletter)$ api/contact.php [L]",
  "",
  "# Permanent redirects (from next.config.ts)",
  ...redirects.map(([s, d]) => `RewriteRule ^${rx(s)}$ ${d} [L,R=301]`),
  "",
  "# Old case viewer links: /case?set=..&id=<post>",
  ...caseMap.flatMap(([id, slug]) => [`RewriteCond %{QUERY_STRING} (^|&)id=${rx(id)}(&|$)`, `RewriteRule ^case$ /case-studies/${slug}? [L,R=301]`]),
  "RewriteRule ^case$ /case-studies? [L,R=301]",
  "",
  "# Clean URLs: /about serves about.html",
  "RewriteCond %{REQUEST_FILENAME} !-f",
  "RewriteCond %{DOCUMENT_ROOT}/$1.html -f",
  "RewriteRule ^(.+)$ $1.html [L]",
  "",
  "<IfModule mod_headers.c>",
  '  Header always set X-Content-Type-Options "nosniff"',
  '  Header always set X-Frame-Options "SAMEORIGIN"',
  '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
  '  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"',
  '  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), browsing-topics=()"',
  '  <FilesMatch "\\.(js|css|woff2?|webp|png|jpg|jpeg|svg|ico|mp4|webm)$">',
  '    Header set Cache-Control "public, max-age=31536000, immutable"',
  "  </FilesMatch>",
  '  <FilesMatch "\\.html$">',
  '    Header set Cache-Control "public, max-age=0, must-revalidate"',
  "  </FilesMatch>",
  "</IfModule>",
  "",
  "<IfModule mod_deflate.c>",
  "  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/rss+xml application/javascript application/json image/svg+xml",
  "</IfModule>",
  "",
  'AddType "application/rss+xml; charset=utf-8" .rss',
  'AddType "text/plain; charset=utf-8" .txt',
  "",
  "# Protect the lead handler config",
  '<Files "config.php">',
  "  Require all denied",
  "</Files>",
  "",
];
fs.writeFileSync(path.join(OUT, ".htaccess"), lines.join("\n"));
fs.rmSync(TMP, { recursive: true, force: true });
console.log(`Done: ${OUT} (${redirects.length} redirects, ${caseMap.length} case links)`);
